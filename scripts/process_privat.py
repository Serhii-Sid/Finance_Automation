import pandas as pd
import os
import glob

# Налаштування відображення: кажемо Pandas показувати ВСІ колонки в терміналі
pd.set_option('display.max_columns', None)  # Не ховати колонки
pd.set_option('display.width', 1000)        # Дозволити таблиці бути широкою
pd.set_option('display.max_colwidth', 16)   # ПІДПИЛКА: додаємо ширину колонкам, щоб не злипалися
pd.set_option('display.expand_frame_repr', False) # ПІДПИЛКА 2: забороняємо Пайтону переносити колонки на новий рядок
pd.set_option('display.max_rows', None)  # Показувати всю таблицю

# ДОВІДНИК КАРТОК: Перетворює технічні маски банків із зірочками на красиві назви.
# Якщо додається нова картка або інший банк, просто допиши її сюди за зразком через кому.
CARDS_DICTIONARY = {
    '5457 **** **** 4169': 'Приват Sid Унів 5457', # присвоїв ім'я карті Sid універсал від приват
    '5168 **** **** 4882': 'Приват Sid Кешбек 4882', # присвоїв ім'я карті Sid нац кешбек від приват
    '4149 **** **** 0707': 'Приват Sid Виплати 0707', # присвоїв ім'я карті Sid для виплат від приват
}
# Крок 1.0: Показуємо шлях до папки з вхідними даними
input_folder = 'input_data'

# Крок 2.0: Шукаємо будь-який файл Excel у цій папці
search_pattern = os.path.join(input_folder, '*.xlsx')
found_files = glob.glob(search_pattern)

# Крок 3.0: Перевіряємо, чи знайшовся файл
if not found_files:
    print("Помилка: У папці input_data немає жодного файлу Excel!")
else:
    print(f"Супер! Знайдено файли для обробки: {len(found_files)}")

    # Крок 3.1: Офіційна перевірка. Показуємо в терміналі список цих трьох файлів
    print(found_files)

    # Крок 3.2: Створюємо порожню коробку (список) для збору очищених таблиць
    all_dataframes = []

    # Крок 4: Запускаємо цикл: для кожного шляху до файлу у нашому списку
    for one_file in found_files:
        print(f" Зараз у черзі на обробку файл: {one_file}")

        # Крок 4.1: Пайтон заглядає у файл і завантажує таблицю в пам'ять (внутрішня робота)
        df_privat = pd.read_excel(one_file, header=1)

        # Крок 4.2: Створюємо список-трафарет із 6 потрібних вам колонок
        useful_columns = [
            'Дата', 
            'Категорія', 
            'Картка', 
            'Опис операції', 
            'Сума в валюті картки', 
            'Залишок на кінець періоду'
        ]
    
        # Крок 4.3: Застосовуємо трафарет — вирізаємо з df_privat лише ці 6 стовпчиків 
        # і створюємо нову чисту таблицю df_filtered
        df_filtered = df_privat[useful_columns].copy()

        # Крок 4.4: Очищення даних. Перетворюємо текст із сумами на справжні числа
        df_filtered['Сума в валюті картки'] = pd.to_numeric(df_filtered['Сума в валюті картки'], errors='coerce')
        df_filtered['Залишок на кінець періоду'] = pd.to_numeric(df_filtered['Залишок на кінець періоду'], errors='coerce')
        df_filtered['Дата'] = pd.to_datetime(df_filtered['Дата'], dayfirst=True, errors='coerce')
        
        # Заміна маски картки на красиву назву з нашого довідника
        for mask, custom_name in CARDS_DICTIONARY.items():
            df_filtered['Картка'] = df_filtered['Картка'].astype(str).str.replace(mask, custom_name, regex=False)

        # Крок 4.5: Генерація унікального цифрового ID ( can be upgraded )
        # Перетворюємо дату у формат чистої строки цифр: YYYYMMDDHHMMSS
        date_str = df_filtered['Дата'].dt.strftime('%Y%m%d%H%M%S')
        # Беремо суму, перетворюємо в ціле число (без копійок) і прибираємо мінус за допомогою abs()
        id_sum = df_filtered['Сума в валюті картки'].fillna(0).astype(int).abs().astype(str)
        # Склеюємо їх через підкреслення в нову колонку
        df_filtered['ID_Транзакції'] = date_str + '_' + id_sum
        df_filtered = df_filtered[['ID_Транзакції', 'Дата', 'Категорія', 'Картка', 'Опис операції', 'Сума в валюті картки', 'Залишок на кінець періоду']]

        # Крок 4.6: Відображаємо лише «верхівку» та «хвіст» таблиці (по 3 рядки)
        print(f"\n--- Файл {one_file} (3 зверху та 3 знизу): ---")
        print(pd.concat([df_filtered.head(3), df_filtered.tail(3)]))

        # Крок 4.7: Кладемо готову таблицю в нашу коробку для майбутнього об'єднання
        all_dataframes.append(df_filtered)

# Крок 4.8 --- НАШ НОВИЙ ОХОРОНЕЦЬ (пишемо без відступів, притиснутим до лівого краю) ---
if len(all_dataframes) > 0:   

    # Крок 5.0: Об'єднуємо всі таблиці з коробки в одну велику базу даних
    df_final = pd.concat(all_dataframes, ignore_index=True)

    # Крок 5.1 (новий): Сортуємо по даті (додай це!)
    df_final = df_final.sort_values(by='Дата', ascending=False)

    # Крок 5.2: Видалення дублікатів
    # drop_duplicates дивиться на стовпчик 'ID_Транзакції'
    # і залишає лише перший знайдений рядок, видаляючи всі наступні з таким самим ID
    df_final = df_final.drop_duplicates(subset=['ID_Транзакції'])

    # Крок 5.3 (додатковий): Скидаємо індекси, щоб нумерація була рівною
    df_final = df_final.reset_index(drop=True)

    # Крок 5.4: Розрахунок загального балансу
    total_balance = df_final['Сума в валюті картки'].sum()

    # Крок 5.5: Офіційна перевірка результату
    print("\n--- ФІНАЛЬНА ОБ'ЄДНАНА ТАБЛИЦЯ ---")
    print(f"Загальна кількість транзакцій: {len(df_final)}")
    print(df_final) # Показуємо об'єднану таблицю повністю 

    # Крок 6: Аналітика — Розрахунок балансу та доходів/витрат

    # Крок 6.1: Розрахунок підсумкових значень
    total_balance = df_final['Сума в валюті картки'].sum() #загальний фінансовий баланс
    total_expenses = df_final[df_final['Сума в валюті картки'] < 0]['Сума в валюті картки'].sum() # загальні витрати
    total_income = df_final[df_final['Сума в валюті картки'] > 0]['Сума в валюті картки'].sum() # загальні доходи

    # Крок 6.2: Виведення фінансового звіту
    print("\n--- ФІНАЛЬНИЙ ФІНАНСОВИЙ ЗВІТ ---")
    print(f"Загальний баланс змін: {round(total_balance, 2)} грн.") #загальний фінансовий баланс
    print(f"Загальні витрати: {round(total_expenses, 2)} грн.") # загальні витрати
    print(f"Загальні доходи: {round(total_income, 2)} грн.") # загальні доходи

    # Крок 10: Групування витрат за категоріями

    # 10.1. Відбираємо тільки витрати (все, що менше за нуль)
    only_expenses = df_final[df_final['Сума в валюті картки'] < 0]

    # 10.2. Групуємо за колонкою "Категорія" та сумуємо суми
    category_summary = only_expenses.groupby('Категорія')['Сума в валюті картки'].sum()

    print("\n--- Витрати за категоріями (Крок 10): ---")
    print(category_summary)